  assert.equal(await page.locator('.speaking').getAttribute('id'),'p-85');
  await event('started',86);assert.equal(await page.locator('.speaking').getAttribute('id'),'p-86');
  assert.deepEqual(await page.evaluate(()=>scrollCalls),[]);
  await event('paused',86);assert.equal(await page.locator('#locateReading').isDisabled(),false);
